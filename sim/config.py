    #   k ≈ 1,300N / (0.06×2m) ≈ 1.1만 N/m 이상. 현재 100 N/m는 실제 로프보다 약 100배 무르다 (고무줄 수준).
    # 실험(2026-11-16, 값은 바꾸지 않고 실행 중에만 교체): k=1만·5만 N/m에서 구조 미션·수상 견인·착용·잡기
    #   시나리오는 정상. 가영 줄 테스트는 기대값을 이 값들에서 계산하므로 바꿔도 그대로 통과한다.
