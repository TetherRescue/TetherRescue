    # 측정(2026-11-16): 배 최대 추력 합 100N, 구조 시나리오 최대 장력 16N, 최대 추력 10초 견인 133N.
    #   → 이 배로는 파단 강도의 1~2%만 걸리므로 1주차는 끊김 기능을 구현하지 않는다 (tether.py가 읽지 않음).
    #   큰 배·파도·충격 하중을 넣을 때 다시 검토.
    BREAK_FORCE = 13000.0   # [가영 / 제안]


